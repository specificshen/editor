/**
 * draco3dgltf ships only Node-flavored Emscripten glue
 * (draco_encoder_gltf_nodejs.js), whose static require("fs")/require("path")
 * can't be bundled for the browser — turbopack fails the whole page with
 * "Module not found: Can't resolve 'fs'". Those requires sit behind the
 * Emscripten ENVIRONMENT_IS_NODE branch, which never runs in the browser (the
 * encoder wasm is fetched over HTTP via locateFile()), so this script stubs
 * them and appends an ESM default export.
 *
 * Re-run after any draco3dgltf upgrade:
 *   bun packages/editor/scripts/vendor-draco-encoder.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '../../..')
const src = join(repoRoot, 'node_modules/draco3dgltf/draco_encoder_gltf_nodejs.js')
const out = join(here, '../src/lib/vendor/draco-encoder-module.js')

let glue = readFileSync(src, 'utf8')
for (const mod of ['fs', 'path']) {
  const needle = `require("${mod}")`
  if (!glue.includes(needle)) {
    throw new Error(`expected ${needle} in the draco encoder glue — format changed?`)
  }
  glue = glue.replaceAll(needle, `__dracoNodeRequire("${mod}")`)
}

const header = `// GENERATED by packages/editor/scripts/vendor-draco-encoder.mjs from
// node_modules/draco3dgltf/draco_encoder_gltf_nodejs.js — do not edit by hand.
// The Node-only require() calls (fs/path, behind the Emscripten
// ENVIRONMENT_IS_NODE branch) are stubbed so the file bundles for the browser.
function __dracoNodeRequire(name) {
  throw new Error(\`draco encoder: node-only module "\${name}" is unavailable in the browser\`)
}
`

mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `${header}${glue}\nexport default DracoEncoderModule\n`)
console.log(`wrote ${out}`)
